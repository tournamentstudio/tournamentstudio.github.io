export const getTheme = (id: string) =>
  themes.find((t) => t.id === id) ?? themes[0];
export const getThemesForSport = (sport: string): ThemePreset[] => {
  const matches = themes.filter((theme) => theme.sports.includes(sport));
  return matches.length
    ? matches
    : themes.filter((theme) => theme.sports.includes("generic"));
};
