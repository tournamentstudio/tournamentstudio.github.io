export const getTheme = (id: string) =>
  themes.find((t) => t.id === id) ?? themes[0];
export const fonts = {
  inter: '"Inter Variable", "Vazirmatn Variable", sans-serif',
  vazirmatn: '"Vazirmatn Variable", sans-serif',
  serif: 'Georgia, "Vazirmatn Variable", serif',
  mono: 'ui-monospace, "Vazirmatn Variable", monospace',
};
export function themeStyle(settings: ThemeSettings): CSSProperties {
  const t = getTheme(settings.preset);
  return {
    "--theme-accent": settings.accent ?? t.accent,
    "--theme-bg": settings.background ?? t.background,
    "--theme-fg": settings.foreground ?? t.foreground,
    "--theme-card": t.card,
    "--theme-muted": t.muted,
    "--theme-radius": `${settings.radius ?? t.radius}px`,
    "--theme-border": `${settings.borderWidth ?? t.border}px`,
    "--theme-font": fonts[settings.font ?? t.font ?? "inter"],
    "--theme-scale": settings.fontScale ?? 1,
    "--theme-spacing": settings.spacing ?? 1,
    "--theme-shadow": t.shadow,
    "--theme-image": settings.backgroundImage
      ? `url("${settings.backgroundImage}")`
      : "none",
  } as CSSProperties;
}
/** Only decoded raster assets enter themes. SVG and remote URLs are excluded. */
export async function readImageAsset(file: File): Promise<string> {
  if (!["image/png", "image/jpeg", "image/webp"].includes(file.type))
    throw new Error("Use PNG, JPEG or WebP.");
  if (file.size > 2 * 1024 * 1024)
    throw new Error("Images must be smaller than 2 MB.");
  const url = URL.createObjectURL(file);
  try {
    const img = new Image();
    img.src = url;
    await img.decode();
    if (img.width * img.height > 16_000_000)
      throw new Error("Image dimensions are too large.");
    const canvas = document.createElement("canvas");
    const scale = Math.min(1, 1600 / Math.max(img.width, img.height));
    canvas.width = Math.max(1, Math.round(img.width * scale));
    canvas.height = Math.max(1, Math.round(img.height * scale));
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Image processing is unavailable.");
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    let encoded = canvas.toDataURL("image/png");
    if (validateRasterAsset(encoded)) return encoded;
    encoded = canvas.toDataURL("image/webp", 0.82);
    if (validateRasterAsset(encoded)) return encoded;
    for (let attempt = 0; attempt < 4; attempt++) {
      canvas.width = Math.max(1, Math.floor(canvas.width * 0.7));
      canvas.height = Math.max(1, Math.floor(canvas.height * 0.7));
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
      encoded = canvas.toDataURL("image/webp", 0.75);
      if (validateRasterAsset(encoded)) return encoded;
    }
    throw new Error("The processed image exceeds the storage limit.");
  } finally {
    URL.revokeObjectURL(url);
  }
}
